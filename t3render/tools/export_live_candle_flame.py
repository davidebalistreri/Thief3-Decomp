"""Embed the existing generated candle meshes in the live viewer."""
import argparse
import hashlib
from pathlib import Path

import scene_pbr_flames


def number(value):
    text = format(value, ".9g")
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("glb", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--candlestick-output", type=Path)
    args = parser.parse_args()
    raw = args.glb.read_bytes()
    positions, normals, indices = scene_pbr_flames.read_geometry(raw)
    if len(positions) > 256 or len(indices) > 1024:
        raise ValueError("flame geometry exceeds the live preview budget")
    def vectors(name, data):
        values = ",\n".join("    {" + ",".join(number(v) for v in item) + "}" for item in data)
        return f"inline constexpr float {name}[][3] = {{\n{values}\n}};\n"
    index_rows = [", ".join(str(v) for v in indices[i:i+24]) for i in range(0, len(indices), 24)]
    header = ("#pragma once\n\n"
              "// Generated by tools/export_live_candle_flame.py from CandleFlame in\n"
              f"// candlestick_high.glb; SHA-256: {hashlib.sha256(raw).hexdigest()}\n"
              "namespace t3render::live::candle_flame_geometry {\n" +
              f'inline constexpr char source_sha256[] = "{hashlib.sha256(raw).hexdigest()}";\n' +
              vectors("positions_m", positions) + vectors("normals", normals) +
              "inline constexpr unsigned indices[] = {\n    " + ",\n    ".join(index_rows) + "\n};\n"
              "} // namespace t3render::live::candle_flame_geometry\n")
    args.output.write_text(header, encoding="utf-8")
    if args.candlestick_output:
        meshes = []
        for name in ("METAL1Goodness_D", "CandleWax"):
            meshes.append(scene_pbr_flames.read_geometry(raw, name, max_vertices=8192, max_indices=30000))
        if sum(len(mesh[0]) for mesh in meshes) > 8192 or sum(len(mesh[2]) for mesh in meshes) > 30000:
            raise ValueError("candlestick geometry exceeds the live preview budget")
        parts = ["#pragma once\n\n", "// Generated from candlestick_high.glb by tools/export_live_candle_flame.py\n",
                 f"// SHA-256: {hashlib.sha256(raw).hexdigest()}\n",
                 "namespace t3render::live::candlestick_geometry {\n",
                 f'inline constexpr char source_sha256[] = "{hashlib.sha256(raw).hexdigest()}";\n']
        for name, (points, normal_values, triangle_indices) in zip(("metal", "wax"), meshes):
            parts.extend((vectors(name + "_positions_m", points), vectors(name + "_normals", normal_values)))
            rows = [", ".join(str(v) for v in triangle_indices[i:i+24])
                    for i in range(0, len(triangle_indices), 24)]
            parts.append(f"inline constexpr unsigned {name}_indices[] = {{\n    " + ",\n    ".join(rows) + "\n};\n")
        parts.append("} // namespace t3render::live::candlestick_geometry\n")
        args.candlestick_output.write_text(''.join(parts), encoding="utf-8")


if __name__ == "__main__":
    main()
